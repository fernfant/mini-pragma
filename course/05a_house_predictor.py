"""
Lesson 5a — House price predictor.

A "middle ground" example between pragma_mini.py (pets, 3 keys) and the
streaming churn predictor (4 keys × 15 events). Here:

  - 10 keys per record (richer structure, closer to real PRAGMA banking events).
  - One record per house (no event sequence — simpler).
  - 5-class price prediction (bargain / cheap / average / expensive / luxury).
  - REALISTIC CORRELATIONS between attributes (beach houses tend to have
    pools, vintage houses are usually smaller, etc.) — this is what gives
    MLM something contextual to learn.

Same PRAGMA recipe applies:

  1. Tokenise each house as (key, value) pairs.
  2. Pre-train via fill-in-the-blank (MLM) — no price labels.
  3. Freeze encoder. Add a 5-way price-classifier head.
  4. Train head on a small labelled set.
  5. Compare to a baseline that doesn't pre-train.

Run:  python3 05a_house_predictor.py
"""

