# ============================================================================
# PART 2 — Architecture (same shape as pragma_mini.py)
# ============================================================================

D_MODEL  = 32
N_HEADS  = 2
N_LAYERS = 2


class Encoder(nn.Module):
    def __init__(self, V, d=D_MODEL, heads=N_HEADS, layers=N_LAYERS, max_len=64):
        super().__init__()
        self.emb = nn.Embedding(V, d)
        self.pos = nn.Embedding(max_len, d)
        layer    = nn.TransformerEncoderLayer(d, heads, d * 2, batch_first=True)
        self.enc = nn.TransformerEncoder(layer, layers)
    def forward(self, x):
        positions = torch.arange(x.size(1), device=x.device)
        return self.enc(self.emb(x) + self.pos(positions))


class MLMHead(nn.Module):
    def __init__(self, V, d=D_MODEL):
        super().__init__()
        self.proj = nn.Linear(d, V)
    def forward(self, h):
        return self.proj(h)


class PriceHead(nn.Module):
    def __init__(self, d=D_MODEL, n_classes=5):
        super().__init__()
        self.proj = nn.Linear(d, n_classes)
    def forward(self, h):
        pooled = h.mean(dim=1)
        return self.proj(pooled)


# ============================================================================
# PART 3 — Pre-train via MLM
# ============================================================================
# Higher mask rate (30%) so the model has to genuinely use context from
# remaining tokens to predict masked ones — that's what forces it to learn
# the inter-attribute correlations.

KEY_IDS = torch.tensor([tok2id[k] for k in KEYS])


def mlm_mask(X_batch, p=0.30):
    X = X_batch.clone()
    y = torch.full_like(X, -100)
    is_value = ~torch.isin(X, KEY_IDS)
    pick = (torch.rand_like(X, dtype=torch.float) < p) & is_value
    y[pick] = X[pick]
    X[pick] = tok2id[MASK]
    return X, y


encoder   = Encoder(V)
mlm_head  = MLMHead(V)
opt       = torch.optim.AdamW(list(encoder.parameters()) + list(mlm_head.parameters()), lr=3e-3)
loss_fn   = nn.CrossEntropyLoss(ignore_index=-100)

total_knobs = sum(p.numel() for p in list(encoder.parameters()) + list(mlm_head.parameters()))
print(f"Pre-training encoder via MLM ({total_knobs:,} knobs, 3000 steps)...")
for step in range(3000):
    idx       = torch.randint(0, N_HOUSES, (128,))
    xb, yb    = mlm_mask(X[idx])
    h         = encoder(xb)
    logits    = mlm_head(h)
    loss      = loss_fn(logits.reshape(-1, V), yb.reshape(-1))
    opt.zero_grad(); loss.backward(); opt.step()
    if step % 500 == 0:
        print(f"  step {step:4d}   MLM loss {loss.item():.3f}")

pretrained_encoder = copy.deepcopy(encoder)
print()


# ============================================================================
# PART 4 — Downstream task: predict price class
# ============================================================================

perm  = torch.randperm(N_HOUSES)
