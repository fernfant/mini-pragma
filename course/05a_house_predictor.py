PAD, MASK = "<pad>", "<mask>"
VALUES = [v for vs in VALUE_BUCKETS.values() for v in vs]
vocab = [PAD, MASK] + KEYS + VALUES
tok2id = {t: i for i, t in enumerate(vocab)}
V = len(vocab)

PRICE_CLASSES = ["bargain", "cheap", "average", "expensive", "luxury"]


def weighted_choice(weights_dict):
    items, weights = zip(*weights_dict.items())
    return random.choices(items, weights=weights, k=1)[0]


def random_house():
    archetype = weighted_choice(ARCHETYPE_WEIGHTS)
    dists = ARCHETYPES[archetype]
    return {k: weighted_choice(dists[k]) for k in KEYS}


def house_price(house):
    """Sum the weights, add some interaction bonuses + noise."""
    p = PRICE_BASE
    for k, v in house.items():
        p += PRICE_WEIGHTS[k][v]
    # A couple of interactions to make the task richer
    if house["neighborhood"] == "beach" and house["pool"] == "haspool":
        p += 80
    if house["age"] == "vintage" and house["condition"] == "poorcond":
        p -= 60
    if house["size"] == "huge" and house["bedrooms"] == "5+bed":
        p += 60
    p += random.gauss(0, 30)
    return max(0, p)


def price_to_class(price):
    if price < 250:   return 0
    if price < 450:   return 1
    if price < 700:   return 2
    if price < 1000:  return 3
    return 4


def encode_house(house):
    ids = []
    for k in KEYS:
        ids.append(tok2id[k])
        ids.append(tok2id[house[k]])
    return ids


